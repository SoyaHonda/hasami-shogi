// Generates src/golden_cases.h from test/golden/ai_cases.txt for the ESP32 `golden` serial
// command (src/main.cpp). The header is not in git: run this before `pio run -e esp32dev`
// (CI does).
//   node tools/gen-golden.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../test/golden/ai_cases.txt', import.meta.url);
const out = new URL('../src/golden_cases.h', import.meta.url);

const cases = [];
readFileSync(src, 'utf8')
  .split(/\r?\n/)
  .forEach((raw, i) => {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) return; // same rule as isAiCaseSkippable
    cases.push({ lineNo: i + 1, line });
  });

const lines = [
  '// Generated by tools/gen-golden.mjs from test/golden/ai_cases.txt. Do not edit; not in git.',
  '#pragma once',
  '',
  'struct GoldenCase {',
  '  int lineNo;          // line number in test/golden/ai_cases.txt',
  '  const char* text;    // the line, for parseAiCase',
  '};',
  '',
  'static const GoldenCase GOLDEN_CASES[] = {',
  ...cases.map((c) => `    {${c.lineNo}, ${JSON.stringify(c.line)}},`),
  '};',
  `static const int GOLDEN_CASE_COUNT = ${cases.length};`,
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${cases.length} cases to src/golden_cases.h`);
